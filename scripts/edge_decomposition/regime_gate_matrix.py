# Detector 1: LT-heuristic (adapted from live-trader/daily_runner.py infer_regime)
# ============================================================================
# Adapted from /Users/claudiu/.openclaw/workspace/live-trader/daily_runner.py
# (READ-ONLY dir; logic copied, not imported, since that module pulls in
# broker-dependent imports at load time). Original breadth/trend/gold-leadership
# heuristic over RISK_ASSETS = {SPY, QQQ, IWM, EFA, EEM, XLE}, DEFENSIVE = {GLD, TLT}.
# Here narrowed to the SPY/QQQ/GLD subset this script fetches (all three are in
# the original RISK_ASSETS/DEFENSIVE sets), which changes the breadth denominator
# from 6 risk assets to 2 (SPY, QQQ) — documented as a fidelity caveat below.
LT_RISK_ASSETS = ("SPY", "QQQ")
LT_DEFENSIVE = ("GLD",)


def lt_heuristic_regime(ret20: dict[str, float]) -> str:
    """ret20: {"SPY": .., "QQQ": .., "GLD": ..} 20-trading-day returns through prior close."""
    risk_positive = sum(1 for s in LT_RISK_ASSETS if ret20.get(s, 0.0) > 0)
    breadth = risk_positive / len(LT_RISK_ASSETS)
    spy20 = ret20.get("SPY", 0.0)
    qqq20 = ret20.get("QQQ", 0.0)
    gld20 = ret20.get("GLD", 0.0)

    risk_on = breadth >= 0.55 and (spy20 > 0 or qqq20 > 0)
    risk_off = breadth <= 0.30 and gld20 > 0

    if risk_off:
        return "risk_off"
    elif risk_on:
        return "risk_on"
    return "mixed"


# ============================================================================
# Detector 2: trend-vol (SPY 200dma + realized-vol percentile)
# ============================================================================
def trendvol_regime(spy_close: float, sma200: float | None, vol20: float | None, vol_pct80: float | None) -> str:
    if sma200 is None:
        return "mixed"
    if spy_close < sma200 and vol20 is not None and vol_pct80 is not None and vol20 > vol_pct80:
        return "risk_off"
    if spy_close > sma200:
        return "risk_on"
    return "mixed"


# ============================================================================
# Detector 3: walk-forward 2-state Gaussian HMM on SPY daily returns
# ============================================================================
# Integrity: state inference for day D uses a model fit only on returns through
# day D-1's close, and only infers using return history through D-1 as well
# (the return "on day D" is not known until D's close, which is also the price
# used to execute D's trade — so even the feature itself must stop at D-1).
# Refit is monthly (first trading day seen of each new calendar month) using an
# expanding window from FETCH_START through the most recently completed prior
# trading day. Between refits, the previously-fit model is reused for daily
# state inference. This guarantees no future data ever enters a decision.
@dataclass
class HMMWalkForward:
    returns: pd.Series  # SPY daily log returns, indexed by date
    _model: object = field(default=None, repr=False)
    _last_refit_month: tuple[int, int] | None = field(default=None, repr=False)
    _risk_off_state: int | None = field(default=None, repr=False)
    refits: int = 0

    def _refit(self, as_of_idx: int):
        from hmmlearn.hmm import GaussianHMM

        train = self.returns.iloc[:as_of_idx].values.reshape(-1, 1)
        if len(train) < 60:
            self._model = None
            return
        model = GaussianHMM(n_components=2, covariance_type="diag", n_iter=100, random_state=42)
        try:
            model.fit(train)
        except Exception:
            self._model = None
            return
        # Identify the risk_off state as the one with lower mean return (ties: higher variance).
        means = model.means_.flatten()
        variances = np.array([np.diag(c)[0] for c in model.covars_]) if model.covariance_type != "diag" else model.covars_.flatten()
        risk_off_state = int(np.argmin(means))
        self._model = model
        self._risk_off_state = risk_off_state
        self.refits += 1

    def state_for(self, d: date) -> str:
        """Regime for day d, using only returns through d's index minus 1 for the training
        cutoff, and returns through d's index minus 1 for inference too (see class docstring).
        """
        if d not in self.returns.index:
            return "mixed"
        idx = self.returns.index.get_loc(d)
        if idx < 60:
            return "mixed"

        month_key = (d.year, d.month)
        if self._last_refit_month != month_key:
            self._refit(idx)  # train on returns[:idx] -> strictly before day d
            self._last_refit_month = month_key

        if self._model is None:
            return "mixed"

        infer_window = self.returns.iloc[:idx].values.reshape(-1, 1)  # strictly before d
        if len(infer_window) < 2:
            return "mixed"
        try:
            states = self._model.predict(infer_window)
        except Exception:
            return "mixed"
        current_state = states[-1]
        return "risk_off" if current_state == self._risk_off_state else "risk_on"


