        "(0.15/0.05); mixed holds the previous day's gate state (hysteresis) to avoid flapping. Thresholds "
        "are mutated on the live DualMomentumStrategy instance immediately before each day's generate_signal() "
        "call — no src/aurel2/ source was modified.",
        "LT-heuristic detector (a2_gate_lt) is a narrowed adaptation of live-trader's daily_runner.py "
        "infer_regime(): original RISK_ASSETS={SPY,QQQ,IWM,EFA,EEM,XLE}, DEFENSIVE={GLD,TLT}; this script only "
        "fetches SPY/QQQ/GLD, so breadth is computed over {SPY,QQQ} (denominator 2, not 6) and defensive "
        "leadership uses GLD only (no TLT). This is a lower-fidelity breadth signal than live-trader's actual "
        "6-asset breadth — a caveat on how directly a2_gate_lt's numbers reflect live-trader's real detector.",
        "trend-vol detector (a2_gate_trendvol): risk_off requires SPY close < 200dma AND 20-day realized vol "
        "(annualized) above its trailing-252-trading-day 80th percentile; risk_on requires SPY close > 200dma; "
