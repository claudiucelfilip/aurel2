def fetch_regime_inputs() -> pd.DataFrame:
    """SPY/QQQ/GLD daily auto-adjusted closes, FETCH_START -> FETCH_END, as a wide DataFrame indexed by date."""
    print(f"Fetching SPY/QQQ/GLD {FETCH_START} -> {FETCH_END} for regime detectors...", file=sys.stderr)
    raw = yf.download(
        ["SPY", "QQQ", "GLD"], start=FETCH_START.isoformat(),
        end=(FETCH_END + timedelta(days=3)).isoformat(),
        auto_adjust=True, progress=False, group_by="ticker",
    )
    cols = {}
    for sym in ["SPY", "QQQ", "GLD"]:
        cols[sym] = raw[sym]["Close"].dropna()
    df = pd.DataFrame(cols)
    df.index = pd.to_datetime(df.index).date
    df = df.sort_index()
    return df


def build_gate_state_series(regime_df: pd.DataFrame) -> dict[str, dict[date, dict]]:
    """Precompute, for every trading day in regime_df, each detector's raw regime label.
    Strictly point-in-time: label for day D only uses data through D-1's close.
    Returns {detector_name: {date: {"regime": ..., diagnostics...}}}.
    """
    dates = list(regime_df.index)
    out: dict[str, dict[date, dict]] = {"lt_heuristic": {}, "trend_vol": {}, "hmm": {}}

    ret20 = regime_df.pct_change(20)
    sma200 = regime_df["SPY"].rolling(200).mean()
    daily_ret = regime_df["SPY"].pct_change()
    vol20 = daily_ret.rolling(20).std() * np.sqrt(252)
    # Trailing 1y (252 trading day) 80th percentile of the vol20 series, expanding-window
    # equivalent computed via rolling window so it's also strictly backward-looking.
    vol_pct80 = vol20.rolling(252, min_periods=60).quantile(0.80)

    log_ret = np.log(regime_df["SPY"] / regime_df["SPY"].shift(1))
    hmm_returns = log_ret.dropna()
    hmm = HMMWalkForward(returns=hmm_returns)

    for i, d in enumerate(dates):
        if i == 0:
            continue
        prev_d = dates[i - 1]

        # --- LT-heuristic: uses ret20 as of prev_d (data through prev close) ---
        r = ret20.loc[prev_d] if prev_d in ret20.index else None
        if r is not None and not r.isna().any():
            regime = lt_heuristic_regime({"SPY": r["SPY"], "QQQ": r["QQQ"], "GLD": r["GLD"]})
        else:
            regime = "mixed"
        out["lt_heuristic"][d] = {"regime": regime}

        # --- trend-vol: SPY close, 200dma, vol20, vol_pct80 all as of prev_d ---
        spy_prev = regime_df["SPY"].get(prev_d)
        sma_prev = sma200.get(prev_d)
        vol_prev = vol20.get(prev_d)
        volpct_prev = vol_pct80.get(prev_d)
        if spy_prev is not None and not pd.isna(spy_prev) and sma_prev is not None and not pd.isna(sma_prev):
            regime = trendvol_regime(
                spy_prev, sma_prev,
                None if vol_prev is None or pd.isna(vol_prev) else vol_prev,
                None if volpct_prev is None or pd.isna(volpct_prev) else volpct_prev,
            )
        else:
            regime = "mixed"
        out["trend_vol"][d] = {"regime": regime}

        # --- hmm: walk-forward, refit monthly, inference strictly through prev_d ---
        regime = hmm.state_for(d)
        out["hmm"][d] = {"regime": regime}

    NOTES.append(f"HMM walk-forward: {hmm.refits} monthly refits performed over {FETCH_START}..{FETCH_END}.")
    return out


# ============================================================================
# Gate wrapper: turns a detector's raw per-day regime into a hysteresis-applied
# gate state, and applies the corresponding thresholds to the strategy object.
# ============================================================================
class RegimeGate:
    def __init__(self, detector_series: dict[date, dict] | None):
        self.detector_series = detector_series  # None => no gate (a2_baseline)
        self.prev_gate_state = "risk_on"  # default start state
        self.episodes: list[dict] = []  # risk_off episodes: {"start": ..., "end": ...}
        self._current_episode_start: date | None = None
        self.days_risk_off = 0
        self.history: list[dict] = []

    def apply(self, strategy: DualMomentumStrategy, d: date):
        if self.detector_series is None:
            strategy.equity_to_defensive_threshold = LIVE_EQ_TO_DEF
            strategy.defensive_to_equity_threshold = LIVE_DEF_TO_EQ
            return "risk_on"

        raw = self.detector_series.get(d, {"regime": "mixed"})["regime"]
        if raw == "mixed":
            gate_state = self.prev_gate_state  # hysteresis
        else:
            gate_state = raw

        if gate_state == "risk_off":
            strategy.equity_to_defensive_threshold = GATED_EQ_TO_DEF
            strategy.defensive_to_equity_threshold = GATED_DEF_TO_EQ
            self.days_risk_off += 1
            if self._current_episode_start is None:
                self._current_episode_start = d
        else:
            strategy.equity_to_defensive_threshold = LIVE_EQ_TO_DEF
            strategy.defensive_to_equity_threshold = LIVE_DEF_TO_EQ
            if self._current_episode_start is not None:
                self.episodes.append({"start": self._current_episode_start.isoformat(), "end": d.isoformat()})
                self._current_episode_start = None

        self.history.append({"date": d.isoformat(), "raw_regime": raw, "gate_state": gate_state})
        self.prev_gate_state = gate_state
        return gate_state

    def finalize(self, last_date: date):
        if self._current_episode_start is not None:
            self.episodes.append({"start": self._current_episode_start.isoformat(), "end": last_date.isoformat()})
            self._current_episode_start = None

    def diagnostics(self) -> dict:
        return {
            "n_risk_off_episodes": len(self.episodes),
            "total_days_risk_off": self.days_risk_off,
            "risk_off_episodes": self.episodes,
        }


